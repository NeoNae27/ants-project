/**
 * Базовая ошибка домена модулей.
 *
 * Используется для ошибок, связанных с:
 * - некорректным состоянием модуля;
 * - неправильной конфигурацией;
 * - невозможным переходом состояния;
 * - ошибками подключения модуля.
 */
export class ModuleDomainError extends Error {
  constructor(
    message: string,

    /**
     * Машиночитаемый код ошибки.
     *
     * Его удобно использовать в:
     * - логах;
     * - UI;
     * - тестах;
     * - обработчиках ошибок.
     */
    public readonly code: string,
  ) {
    super(message)
    this.name = 'ModuleDomainError'
  }
}
/**
 * ModuleLifecycleState описывает жизненный цикл модуля.
 *
 * Это не то же самое, что текущее выполнение.
 * Например, модуль может быть ACTIVE, но прямо сейчас ничего не делать.
 */
export enum ModuleLifecycleState {
  /**
   * Модуль создан, но ещё не инициализирован.
   */
  NEW = 'new',

  /**
   * Модуль прошёл первичную инициализацию.
   */
  INITIALIZED = 'initialized',

  /**
   * Модуль активен и может участвовать в симуляции.
   */
  ACTIVE = 'active',

  /**
   * Модуль временно приостановлен.
   */
  SUSPENDED = 'suspended',

  /**
   * Модуль неисправен.
   */
  FAILED = 'failed',

  /**
   * Модуль выведен из эксплуатации.
   */
  DECOMMISSIONED = 'decommissioned',
}
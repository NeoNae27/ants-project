/**
 * DeviceExecutionState описывает текущее выполнение устройства.
 *
 * В отличие от lifecycle state, это "что устройство делает сейчас":
 * ждёт, работает, спит, на паузе или остановлено.
 */
export enum DeviceExecutionState {
  /**
   * Устройство ничего не выполняет.
   */
  IDLE = 'idle',

  /**
   * Устройство выполняет активную работу.
   */
  RUNNING = 'running',

  /**
   * Устройство находится в режиме сна на уровне выполнения.
   */
  SLEEPING = 'sleeping',

  /**
   * Выполнение временно приостановлено.
   */
  PAUSED = 'paused',

  /**
   * Выполнение остановлено.
   */
  STOPPED = 'stopped',
}

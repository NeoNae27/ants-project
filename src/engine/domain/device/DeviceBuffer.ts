/**
 * MessageBuffer — простая ограниченная очередь сообщений.
 *
 * Это общий shape буфера: конкретные правила вытеснения,
 * доставки и retry должны задаваться тем доменом, который его использует.
 */
export type MessageBuffer<T> = {
  /**
   * Максимальное количество элементов в очереди.
   */
  capacity: number

  /**
   * Очередь сообщений в порядке обработки.
   */
  queue: T[]
}

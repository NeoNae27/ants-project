/**
 * DeviceLifecycleState описывает жизненный цикл устройства.
 *
 * Это стадия существования устройства в проекте, а не то,
 * выполняет ли оно прямо сейчас какую-то операцию.
 */
export enum DeviceLifecycleState {
  /**
   * Устройство создано, но ещё не подготовлено к работе.
   */
  NEW = 'new',

  /**
   * Устройство проходит первичную настройку или привязку.
   */
  COMMISSIONING = 'commissioning',

  /**
   * Устройство привязано к сети/шлюзу, но ещё не полностью готово.
   */
  BOUND = 'bound',

  /**
   * Устройство получило конфигурацию и готово к активации.
   */
  PROVISIONED = 'provisioned',

  /**
   * Устройство активно и может участвовать в симуляции.
   */
  ACTIVE = 'active',

  /**
   * Устройство временно находится в режиме сна.
   */
  SLEEP = 'sleep',

  /**
   * Устройство потеряло связь с ожидаемой сетью или владельцем.
   */
  ORPHANED = 'orphaned',

  /**
   * Устройство находится в ошибочном состоянии.
   */
  FAULT = 'fault',

  /**
   * Устройство выведено из эксплуатации.
   */
  DECOMMISSIONED = 'decommissioned',
}

/**
 * DeviceMeta — дополнительные данные устройства.
 *
 * Эти данные не определяют поведение DeviceCore напрямую,
 * но нужны для отображения, поиска, сохранения проекта и debug.
 */
export type DeviceMeta = {
  /**
   * Время создания устройства.
   */
  createdAt: number

  /**
   * Время последнего изменения доменного состояния устройства.
   */
  updatedAt: number

  /**
   * Координаты устройства.
   *
   * Можно использовать как условные координаты симуляции (x/y),
   * так и географические координаты (lat/lon).
   */

  // QUE: Move to DeviceCore?
  location?: {
    x?: number
    y?: number
    lat?: number
    lon?: number
  }

  /**
   * Свободные метки для группировки и фильтрации устройств.
   */
  tags?: string[]

  /**
   * Человекочитаемое описание устройства.
   */
  description?: string
}

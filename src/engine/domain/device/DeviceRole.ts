/**
 * DeviceRole описывает роль устройства в сети или симуляции.
 *
 * Роль влияет на то, как устройство участвует в обмене данными:
 * - node собирает или производит данные;
 * - repeater помогает передавать данные дальше;
 * - gateway связывает сеть устройств с внешней системой.
 */
export enum DeviceRole {
  /**
   * Конечное устройство: сенсор, исполнительный узел или виртуальная нода.
   */
  NODE = 'node',

  /**
   * Промежуточное устройство для ретрансляции сообщений.
   */
  REPEATER = 'repeater',

  /**
   * Шлюз между устройствами и внешним приложением/сервером.
   */
  GATEWAY = 'gateway'
}

/**
 * LoRaRuntimeState описывает текущее радио-состояние LoRa-модуля.
 *
 * Это не lifecycle state.
 *
 * Lifecycle state говорит, существует ли модуль и активен ли он в системе.
 * Runtime state говорит, что делает радио-модуль прямо сейчас.
 */
export enum LoRaRuntimeState {
  /**
   * Радиомодуль находится в режиме сна.
   */
  SLEEP = 'sleep',

  /**
   * Радиомодуль готов к работе, но сейчас не принимает и не передаёт.
   */
  STANDBY = 'standby',

  /**
   * Радиомодуль находится в режиме приёма.
   */
  RX = 'rx',

  /**
   * Радиомодуль находится в режиме передачи.
   */
  TX = 'tx',

  /**
   * Радиомодуль подключён/инициализирован.
   */
  CONNECTED = 'connected',

  /**
   * Качество связи снижено.
   */
  DEGRADED = 'degraded',

  /**
   * Ошибка радиомодуля.
   */
  ERROR = 'error',
}